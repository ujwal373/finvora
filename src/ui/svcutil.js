import { FinError } from '../sim/Finance.js';

export const SIM_NOTE = '<div class="sim-note">Fictional simulation data · generated by FinVora · not real market prices</div>';
export const cls = (v) => (v >= 0 ? 'up' : 'down');
export const num = (v) => Number(String(v).replace(/[^0-9.]/g, ''));

export function act(ctx, fn, ok) {
  try { const r = fn(); ctx.changed(typeof ok === 'function' ? ok(r) : ok); return r ?? true; }
  catch (e) { if (e instanceof FinError) ctx.error(e.message); else { console.error(e); ctx.error('Something went wrong.'); } return null; }
}

/** Re-render on simulated-time ticks and trades, but never while the player is typing in this panel. */
export function live(ctx, node, render) {
  return ctx.fin.on(() => {
    const a = document.activeElement;
    if (a && node.contains(a) && (a.tagName === 'INPUT' || a.tagName === 'SELECT')) return;
    if (node.isConnected) render();
  });
}
