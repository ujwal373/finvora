import { el, esc, $ } from './dom.js';
import { formatINR } from '../config.js';

// Interactive exhibits inside Milestone 1 buildings. Every number is computed live from inputs.
// Returns { node, destroy }.

export function exhibit(id, ctx) {
  if (id === 'ticker') return tickerBoard(ctx.market);
  if (id === 'interest') return interestWall();
  if (id === 'rule72') return doublingLab();
  return null;
}

// ---------------------------------------------------------------- Stock Exchange: market board
function tickerBoard(market) {
  const node = el(`<div>
    <div class="fw-msg info" style="margin-top:0"><b>Fictional simulation data.</b> These companies do not exist. Prices are generated by FinVora's simulator (random walk, one tick = one simulated trading hour) and are not real NSE or BSE prices.</div>
    <div style="overflow-x:auto;margin-top:.8rem"><table class="board"><thead><tr><th>Symbol</th><th>Company</th><th>Sector</th><th class="r">Price (₹)</th><th class="r">Since open</th><th class="r">Volatility</th></tr></thead><tbody></tbody></table></div>
    <div class="muted" style="font-size:.78rem;margin-top:.6rem">Source: FinVora fictional simulator · Updates every 2 s · Simulated tick #<span data-t>0</span></div>
  </div>`);
  const body = $(node, 'tbody');
  const render = () => {
    body.innerHTML = market.stocks.map((s) => {
      const ch = market.changePct(s), cls = ch >= 0 ? 'up' : 'down';
      const flash = s.price > s.last ? 'up' : s.price < s.last ? 'down' : '';
      return `<tr><td><b>${esc(s.symbol)}</b></td><td>${esc(s.name)}</td><td class="muted">${esc(s.sector)}</td>
        <td class="r ${flash}">${s.price.toFixed(2)}</td><td class="r ${cls}">${ch >= 0 ? '+' : ''}${ch.toFixed(2)}%</td><td class="r muted">${Math.round(s.vol * 100)}% p.a.</td></tr>`;
    }).join('');
    $(node, '[data-t]').textContent = market.ticks;
  };
  render();
  const off = market.onTick(render);
  return { node, destroy: off };
}

// ---------------------------------------------------------------- Bank: simple vs compound interest
export function interestMaths(P, ratePct, years, n) {
  const r = ratePct / 100;
  const simple = P * (1 + r * years);
  const compound = P * Math.pow(1 + r / n, n * years);
  return { simple, compound, diff: compound - simple };
}

function interestWall() {
  const node = el(`<div>
    <p class="muted" style="margin-top:0">Simple interest pays only on the original amount. Compound interest also pays on interest already earned. Move the sliders and watch the gap grow with time.</p>
    <div class="range-row"><label for="iw-p">Principal</label><output data-o="p"></output><input id="iw-p" type="range" min="10000" max="1000000" step="10000" value="100000"></div>
    <div class="range-row"><label for="iw-r">Annual interest rate</label><output data-o="r"></output><input id="iw-r" type="range" min="1" max="15" step="0.25" value="7"></div>
    <div class="range-row"><label for="iw-y">Years</label><output data-o="y"></output><input id="iw-y" type="range" min="1" max="30" step="1" value="10"></div>
    <label class="fw-label" for="iw-n">Compounding frequency</label>
    <select id="iw-n" class="fw-input"><option value="1">Yearly (n = 1)</option><option value="2">Half-yearly (n = 2)</option><option value="4" selected>Quarterly (n = 4)</option><option value="12">Monthly (n = 12)</option></select>
    <div class="grid-2" style="margin-top:.9rem">
      <div class="stat"><div class="k">Simple interest total</div><div class="v" data-s></div></div>
      <div class="stat"><div class="k">Compound interest total</div><div class="v" style="color:var(--fw-green)" data-c></div></div>
    </div>
    <div class="stat" style="margin-top:.7rem"><div class="k">Extra earned from compounding</div><div class="v" style="color:var(--fw-gold-2)" data-d></div></div>
    <svg viewBox="0 0 300 120" style="width:100%;height:auto;margin-top:.8rem" data-chart aria-label="Growth chart"></svg>
    <div class="section-h">Formulas and your numbers</div>
    <div class="formula" data-f></div>
    <div class="disclaimer">Assumptions: a constant rate, no withdrawals, no tax and no inflation. Many Indian bank FDs compound quarterly; check the actual terms of any real deposit. Educational illustration, not financial advice.</div>
  </div>`);
  const q = (s) => $(node, s);
  const update = () => {
    const P = +q('#iw-p').value, R = +q('#iw-r').value, Y = +q('#iw-y').value, n = +q('#iw-n').value;
    const m = interestMaths(P, R, Y, n);
    q('[data-o="p"]').textContent = formatINR(P);
    q('[data-o="r"]').textContent = `${R.toFixed(2)}%`;
    q('[data-o="y"]').textContent = `${Y} yr`;
    q('[data-s]').textContent = formatINR(m.simple);
    q('[data-c]').textContent = formatINR(m.compound);
    q('[data-d]').textContent = formatINR(m.diff);
    q('[data-f]').textContent =
      `Simple:   A = P × (1 + r × t)\n          = ${P.toLocaleString('en-IN')} × (1 + ${(R / 100).toFixed(4)} × ${Y}) = ${Math.round(m.simple).toLocaleString('en-IN')}\n\n` +
      `Compound: A = P × (1 + r/n)^(n × t)\n          = ${P.toLocaleString('en-IN')} × (1 + ${(R / 100).toFixed(4)}/${n})^(${n} × ${Y}) = ${Math.round(m.compound).toLocaleString('en-IN')}`;
    // Chart: both curves year by year
    const pts = (fn) => Array.from({ length: Y + 1 }, (_, t) => fn(t));
    const s = pts((t) => P * (1 + (R / 100) * t)), c = pts((t) => P * Math.pow(1 + R / 100 / n, n * t));
    const max = Math.max(...c), X = (t) => 8 + (t / Y) * 284, Yp = (v) => 112 - ((v - P * 0.95) / (max - P * 0.95 || 1)) * 100;
    const path = (arr) => arr.map((v, t) => `${t ? 'L' : 'M'}${X(t).toFixed(1)},${Yp(v).toFixed(1)}`).join('');
    q('[data-chart]').innerHTML = `<rect x="0" y="0" width="300" height="120" rx="8" fill="#0f1114"/>
      <path d="${path(s)}" fill="none" stroke="#9aa1ab" stroke-width="2"/><path d="${path(c)}" fill="none" stroke="#2fbf71" stroke-width="2.5"/>
      <text x="10" y="16" fill="#2fbf71" font-size="10" font-family="system-ui">Compound</text><text x="70" y="16" fill="#9aa1ab" font-size="10" font-family="system-ui">Simple</text>
      <text x="292" y="116" fill="#6b727c" font-size="9" text-anchor="end" font-family="system-ui">year ${Y}</text>`;
  };
  node.querySelectorAll('input,select').forEach((i) => i.addEventListener('input', update));
  update();
  return { node, destroy() {} };
}

// ---------------------------------------------------------------- Academy: Rule of 72
export function doublingMaths(ratePct) {
  const rule = 72 / ratePct;
  const exact = Math.log(2) / Math.log(1 + ratePct / 100);
  return { rule, exact, errorPct: ((rule - exact) / exact) * 100 };
}

function doublingLab() {
  const node = el(`<div>
    <p class="muted" style="margin-top:0">How long until money doubles at a fixed yearly return? Compare the mental shortcut with the exact answer.</p>
    <div class="range-row"><label for="dl-r">Annual return</label><output data-o></output><input id="dl-r" type="range" min="1" max="30" step="0.5" value="8"></div>
    <div class="grid-2" style="margin-top:.9rem">
      <div class="stat"><div class="k">Rule of 72 estimate</div><div class="v" data-rule></div></div>
      <div class="stat"><div class="k">Exact doubling time</div><div class="v" style="color:var(--fw-green)" data-exact></div></div>
    </div>
    <div class="stat" style="margin-top:.7rem"><div class="k">Shortcut error</div><div class="v" data-err></div></div>
    <div class="section-h">Formulas</div>
    <div class="formula" data-f></div>
    <div class="section-h">Where the shortcut drifts</div>
    <div style="overflow-x:auto"><table class="board"><thead><tr><th>Return</th><th class="r">Rule of 72</th><th class="r">Exact</th><th class="r">Error</th></tr></thead><tbody data-tbl></tbody></table></div>
    <div class="disclaimer">Assumes a constant annual return compounded yearly. Real investment returns vary from year to year and are not guaranteed.</div>
  </div>`);
  const q = (s) => $(node, s);
  q('[data-tbl]').innerHTML = [2, 4, 6, 8, 10, 12, 18, 24, 30].map((r) => {
    const m = doublingMaths(r);
    return `<tr><td>${r}%</td><td class="r">${m.rule.toFixed(2)} yr</td><td class="r">${m.exact.toFixed(2)} yr</td><td class="r ${Math.abs(m.errorPct) > 3 ? 'down' : 'muted'}">${m.errorPct >= 0 ? '+' : ''}${m.errorPct.toFixed(1)}%</td></tr>`;
  }).join('');
  const update = () => {
    const r = +q('#dl-r').value, m = doublingMaths(r);
    q('[data-o]').textContent = `${r.toFixed(1)}%`;
    q('[data-rule]').textContent = `${m.rule.toFixed(2)} years`;
    q('[data-exact]').textContent = `${m.exact.toFixed(2)} years`;
    q('[data-err]').textContent = `${m.errorPct >= 0 ? '+' : ''}${m.errorPct.toFixed(2)}%`;
    q('[data-f]').textContent = `Rule of 72:  t ≈ 72 ÷ ${r} = ${m.rule.toFixed(3)}\nExact:       t = ln 2 ÷ ln(1 + ${(r / 100).toFixed(3)}) = ${m.exact.toFixed(3)}`;
  };
  q('#dl-r').addEventListener('input', update);
  update();
  return { node, destroy() {} };
}
